import Foundation

extension Hotkey {
    /// The shortcut as macOS menus show it, e.g. `⌥Space` or `⌃⌥⇧⌘K` (ANSI key names).
    public var displayText: String {
        var text = ""
        if modifiers.contains(.control) { text += "⌃" }
        if modifiers.contains(.option) { text += "⌥" }
        if modifiers.contains(.shift) { text += "⇧" }
        if modifiers.contains(.command) { text += "⌘" }
        return text + (Self.keyNames[keyCode] ?? "Key \(keyCode)")
    }

    /// Why this shortcut cannot be the launcher hotkey, or nil when it can.
    public var problem: String? {
        if modifiers.isDisjoint(with: [.command, .option, .control]) {
            return "Use at least one of ⌘, ⌥ or ⌃"
        }
        if keyCode == Self.space, modifiers == [.command] { return "⌘Space is the Spotlight shortcut" }
        if keyCode == Self.space, modifiers == [.command, .option] { return "⌥⌘Space opens Spotlight in Finder" }
        return nil
    }

    private static let space = 49

    /// Virtual key codes of the ANSI layout.
    private static let keyNames: [Int: String] = [
        0: "A", 1: "S", 2: "D", 3: "F", 4: "H", 5: "G", 6: "Z", 7: "X", 8: "C", 9: "V",
        11: "B", 12: "Q", 13: "W", 14: "E", 15: "R", 16: "Y", 17: "T",
        18: "1", 19: "2", 20: "3", 21: "4", 22: "6", 23: "5", 24: "=", 25: "9", 26: "7",
        27: "-", 28: "8", 29: "0", 30: "]", 31: "O", 32: "U", 33: "[", 34: "I", 35: "P",
        36: "↩", 37: "L", 38: "J", 39: "'", 40: "K", 41: ";", 42: "\\", 43: ",", 44: "/",
        45: "N", 46: "M", 47: ".", 48: "⇥", 49: "Space", 50: "`", 51: "⌫", 53: "⎋",
        117: "⌦", 115: "↖", 119: "↘", 116: "⇞", 121: "⇟",
        122: "F1", 120: "F2", 99: "F3", 118: "F4", 96: "F5", 97: "F6", 98: "F7", 100: "F8",
        101: "F9", 109: "F10", 103: "F11", 111: "F12",
        123: "←", 124: "→", 125: "↓", 126: "↑",
    ]
}
